def _f(key: str, name: str, category: str, formula: str, bands: str = "", **more) -> FormulaDTO:
    """A row; ``bands`` is a space-separated list of roles, ``use_cases`` a ";"-separated string."""
    use_cases = more.pop("use_cases", "")
    if isinstance(use_cases, str):
        use_cases = tuple(part.strip() for part in use_cases.split(";") if part.strip())
    for name_ in ("params", "aliases"):
        if isinstance(more.get(name_), str):
            more[name_] = tuple(more[name_].split())
    return FormulaDTO(key=key, name=name, category=category, formula=formula, analysis=ANALYSIS_OF[category],
                      bands=tuple(bands.split()), use_cases=use_cases, **more)


